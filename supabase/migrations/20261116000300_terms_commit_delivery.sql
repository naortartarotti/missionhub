-- N2 job terms card, drop 1, part 3 of 3: snapshot at commit, agreement, ownership, look-back.
--
--   BR-11/BR-12  Both submit RPCs take p_terms_version (dropped and recreated, not overloaded). The
--                version check runs after the preconditions and BEFORE N1's submission gate: a stale or
--                foreign version returns outcome `terms_changed` with an audit event only (no referral,
--                fingerprint, hit row, sticky stop, consent or email). The snapshot (terms version,
--                default rule, frozen estimate, client key) is written inside the existing R2-1 block,
--                so nothing raises after the gate.
--   BR-14        N9's token issuance and resend are not touched.
--   BR-16/BR-17  The agreement is built from the snapshot rule; legacy referrals as before.
--   BR-18/BR-19  app.deliver_referral sets ownership = delivery + effective T9 months (ET), or 12
--                months without a snapshot. respond_candidate_request no longer sets it.
--   BR-3 (Q1)    Candidate-confirmed delivery: snapshot referrals need the full predicate, legacy
--                referrals keep today's check.
--   BR-20        Prior-presentation look-back = delivery − effective T9 months (legacy: 6);
--                get_referral_presentation returns the bound for the hiring side.
--   Drop 1       report_hire refuses snapshot referrals with `hire_terms_pending` (removed in drop 2).
--
-- Every body below is copied verbatim from the live definition named above it; N2 edits are marked
-- "-- N2". Generated by a script that asserts each edit applies exactly once.
-- ---------------------------------------------------------------------------
-- Recorded-authorization path (live: 20261113001100_qa_round2.sql)
-- ---------------------------------------------------------------------------
drop function public.submit_referral(uuid, uuid, text[], uuid[], uuid, text, text, boolean, jsonb);
create function public.submit_referral(
  p_candidate uuid,
  p_job uuid,
  p_fields text[],
  p_document_ids uuid[],
  p_consent uuid,
  p_idempotency_key text,
  p_terms_version uuid,  -- N2: the terms version the submitter was shown (BR-12)
  p_note text default null,
  p_acknowledge_pending boolean default false,
  p_new_consent jsonb default null
) returns table (outcome text, referral_id uuid, reference text)
language plpgsql security definer set search_path = '' as $$
#variable_conflict use_column
declare
  c public.candidates;
  j public.jobs;
  k public.candidate_consents;
  v_existing uuid;
  v_ref uuid;
  v_consent uuid;
  v_basis text;
  v_scope text;
  v_evidence text;
  g record;
  v_terms public.job_terms_versions;  -- N2
  v_rule uuid;                       -- N2
  v_estimate bigint;                 -- N2
begin
  if auth.uid() is null then raise exception 'unauthenticated' using errcode = '28000'; end if;
  -- Same bucket as the Server Action used to consume (B-1): direct PostgREST calls are limited
  -- too, and the limit is checked before anything else runs (AC-18).
  perform app.enforce_rate_limit('referral.submit', 30, 3600);
  if p_idempotency_key is null or char_length(p_idempotency_key) not between 8 and 200 then
    raise exception 'invalid_idempotency_key' using errcode = '22023';
  end if;

  select r.id into v_existing from public.referrals r where r.idempotency_key = p_idempotency_key;
  if v_existing is not null then
    if not app.can_see_referral(v_existing) then raise exception 'forbidden' using errcode = '42501'; end if;
    return query select 'created'::text, v_existing, null::text;
    return;
  end if;

  perform app.assert_referable(p_candidate, p_job, p_fields);
  select * into c from public.candidates where id = p_candidate;
  -- N2: serialise with save_job_terms (which locks the job FOR UPDATE) so the version read here is current.
  select * into j from public.jobs where id = p_job for share;

  if p_consent is not null then
    select * into k from public.candidate_consents where id = p_consent;
    if not found or k.candidate_id <> c.id or k.kind <> 'job_sharing' or k.job_id <> j.id
       or k.revoked_at is not null or (k.expires_at is not null and k.expires_at < now()) then
      raise exception 'sharing_authorization_missing' using errcode = 'P0001';
    end if;
    v_consent := k.id;
  elsif p_new_consent is not null and jsonb_typeof(p_new_consent) = 'object' then
    v_basis := coalesce(nullif(p_new_consent->>'legal_basis', ''), 'consent');
    v_scope := btrim(coalesce(p_new_consent->>'scope', ''));
    v_evidence := btrim(coalesce(p_new_consent->>'evidence', ''));
    if v_basis not in ('consent', 'contract', 'legitimate_interest', 'other_documented')
       or char_length(v_scope) not between 1 and 1000 or char_length(v_evidence) not between 5 and 2000 then
      raise exception 'sharing_authorization_missing' using errcode = 'P0001';
    end if;
  else
    raise exception 'sharing_authorization_missing' using errcode = 'P0001';
  end if;
  perform app.assert_documents_shareable(c.id, p_document_ids);

  -- N2 (BR-11): the default rule at commit. A missing default is a precondition failure, before the gate.
  select cr.id into v_rule from public.commission_rules cr where cr.is_default and cr.retired_at is null order by cr.version desc limit 1;
  if v_rule is null then raise exception 'no_default_commission_rule' using errcode = 'P0001'; end if;
  -- N2 (BR-12): the version shown must still be the job's current one. Before the gate: a stale view
  -- can't trigger a stop, and nothing but the rate-limit hit and this audit event is written.
  v_terms := app.current_job_terms(j.id);
  if p_terms_version is null or p_terms_version is distinct from v_terms.id then
    perform app.audit(c.organization_id, 'referral.terms_changed', 'job', j.id, '{}');
    return query select 'terms_changed'::text, null::uuid, null::text;
    return;
  end if;
  v_estimate := app.terms_estimate(v_terms.fee_basis, v_terms.rate_bps, v_terms.flat_fee_minor, v_terms.min_fee_minor,
                                   j.share_salary, j.salary_min, j.salary_max);

  select * into g from app.submission_gate(c.id, j.id, c.organization_id, j.organization_id, p_acknowledge_pending);
  if g.gate_outcome is not null then
    return query select g.gate_outcome, null::uuid, g.gate_reference;
    return;
  end if;

  -- R2-1: nothing may raise after the gate (a raise would roll back the rate-limit hit and the hit
  -- log). Everything that can fail was validated above; races are turned into a returned code.
  begin
  if v_consent is null then
    insert into public.candidate_consents (organization_id, candidate_id, kind, job_id, legal_basis, scope, evidence, recorded_by)
    values (c.organization_id, c.id, 'job_sharing', j.id, v_basis::public.legal_basis, v_scope, v_evidence, auth.uid())
    returning id into v_consent;
  end if;

  insert into public.referrals (job_id, source_org_id, source_user_id, target_org_id, idempotency_key,
                                job_title_snapshot, candidate_label,
                                terms_version_id, commission_rule_id, fee_estimate_minor)  -- N2 (BR-11)
  values (j.id, c.organization_id, auth.uid(), j.organization_id, p_idempotency_key, j.title,
          app.referral_label(c.id, p_fields),
          v_terms.id, v_rule, v_estimate)
  returning id into v_ref;
  -- N2 (BR-15): the client key at commit, closed table.
  insert into app.referral_commit_keys (referral_id, client_key) values (v_ref, app.client_key(j.client_name));

  insert into public.referral_candidate_links (referral_id, candidate_id, organization_id, consent_id)
  values (v_ref, c.id, c.organization_id, v_consent);
  insert into app.referral_presentations (referral_id, source_org_id, target_org_id, job_id, candidate_id)
  values (v_ref, c.organization_id, j.organization_id, j.id, c.id);

  insert into public.referral_status_events (referral_id, from_status, to_status, actor_id, actor_side, reason)
  values (v_ref, null, 'submitted', auth.uid(), 'source', left(p_note, 2000));

  perform app.deliver_referral(v_ref, v_consent, p_fields, p_document_ids, p_note, auth.uid());
  perform app.audit(c.organization_id, 'referral.submitted', 'referral', v_ref,
    jsonb_build_object('fields', to_jsonb(p_fields), 'documents', coalesce(cardinality(p_document_ids), 0)));
  exception when others then
    return query select app.safe_error_code(sqlstate, sqlerrm), null::uuid, null::text;
    return;
  end;
  return query select 'created'::text, v_ref, null::text;
end $$;
revoke execute on function public.submit_referral(uuid, uuid, text[], uuid[], uuid, text, uuid, text, boolean, jsonb) from public, anon;
grant execute on function public.submit_referral(uuid, uuid, text[], uuid[], uuid, text, uuid, text, boolean, jsonb) to authenticated;

